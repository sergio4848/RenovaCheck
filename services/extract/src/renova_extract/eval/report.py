"""Markdown evaluation report (docs/EVAL_REPORT.md) from the JSON files written by the eval tasks.

Everything shown comes from ``data/eval/*.json``; the output only changes when the measurements
change (timings and the generation date aside).
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

SKIPPED = "uruchomienie pominięte"


def render(eval_dir: Path) -> str:
    summary = _load(eval_dir / "summary.json") or {}
    classification = _load(eval_dir / "classification.json")
    extraction = _load(eval_dir / "extraction.json")
    rules = _load(eval_dir / "rules.json")
    bench = _load(eval_dir / "ocr_bench.json")

    parts = [
        "<!-- Generated by `make eval` from data/eval/*.json. Do not edit by hand. -->",
        "# RenovaCheck - evaluation report",
        "",
        f"Generated {summary.get('generated_at', '—')} · OCR: `{summary.get('ocr', '—')}` · "
        "synthetic data only (`tools/synth`).",
        "",
        *_dataset(summary),
        *_thresholds(summary),
        *_classification(classification),
        *_extraction(extraction),
        *_rules(rules),
        *_timings(summary, classification, extraction, rules),
        *_ocr_bench(bench),
    ]
    return "\n".join(parts).rstrip() + "\n"


def _load(path: Path) -> Any:
    return json.loads(path.read_text()) if path.exists() else None


def _pct(value: float | None) -> str:
    return "—" if value is None else f"{value:.1%}"


def _sec(value: float | None) -> str:
    if value is None:
        return "—"
    return f"{value * 1000:.0f} ms" if value < 1 else f"{value:.2f} s"


def _ratio(tp: int, other: int) -> float | None:
    return tp / (tp + other) if tp + other else None


def _cell(text: Any) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: list[list[Any]], align: str | None = None) -> list[str]:
    spec = align or "l" + "r" * (len(header) - 1)
    marks = ["---:" if a == "r" else ":---" for a in spec]
    return [
        "| " + " | ".join(header) + " |",
        "| " + " | ".join(marks) + " |",
        *("| " + " | ".join(_cell(c) for c in row) + " |" for row in rows),
        "",
    ]


def _dataset(summary: dict[str, Any]) -> list[str]:
    data = summary.get("dataset")
    if not data:
        return []
    rows = [
        [q, data["documents"].get(q, 0), data["pages"].get(q, 0)]
        for q in sorted(set(data["documents"]) | set(data["pages"]))
    ]
    rows.append(["**all**", sum(data["documents"].values()), sum(data["pages"].values())])
    return [
        "## Dataset",
        "",
        f"{data['cases']} cases (seeds {', '.join(map(str, data['seeds']))}), "
        f"{data['injected_errors']} injected errors, {data['expected_findings']} expected findings. "
        f"Ruleset: {data['ruleset']} rules, lock `{data['ruleset_digest'][:12]}`; "
        f"field dictionary v{data['fields_version']}.",
        "",
        *_table(["quality", "documents", "pages"], rows),
    ]


def _thresholds(summary: dict[str, Any]) -> list[str]:
    checks = summary.get("checks")
    if not checks:
        return []
    rows = [[c["name"], c["target"], c["value"], "✅ pass" if c["ok"] else "❌ fail"] for c in checks]
    return ["## Acceptance thresholds", "", *_table(["check", "target", "measured", "result"], rows, "llll")]


def _classification(report: dict[str, Any] | None) -> list[str]:
    if report is None:
        return []
    rows = [
        [q, f"{c['correct']}/{c['total']}", _pct(c["correct"] / c["total"] if c["total"] else None)]
        for q, c in report["by_quality"].items()
        if c["total"]
    ]
    rows.append(["**all**", f"{report['correct']}/{report['total']}", _pct(report["accuracy"])])
    lines = ["## Document type classification", "", *_table(["quality", "correct", "accuracy"], rows)]
    if report["errors"]:
        lines += _table(
            ["document", "expected", "predicted", "quality"],
            [[e["doc_id"], e["expected"], e["predicted"] or "unknown", e["quality"]] for e in report["errors"]],
            "llll",
        )
    else:
        lines += ["No misclassified documents.", ""]
    return lines


def _extraction(report: dict[str, Any] | None) -> list[str]:
    if report is None:
        return []
    docs = report["documents"]
    rows = []
    for name, per_quality in [*report["fields"].items(), ("**all**", report["overall"])]:
        clean, scan = per_quality.get("clean", {}), per_quality.get("scan", {})
        rows.append(
            [
                name,
                _pct(clean.get("precision")),
                _pct(clean.get("recall")),
                _pct(clean.get("bbox_hit_rate")),
                _pct(scan.get("precision")),
                _pct(scan.get("recall")),
                scan.get("unreadable", 0),
            ]
        )
    lines = [
        "## Field extraction",
        "",
        f"Per (document, field) against the ground truth: {docs.get('clean', 0)} clean (vector) documents, "
        f"{docs.get('scan', 0)} noisy scans. A value counts when its normalised form matches; *bbox* is the "
        "share of correct values whose box overlaps the true one (IoU ≥ 0.5). Unreadable fields are "
        "abstentions (counted as misses, never as wrong values).",
        "",
        *_table(["field", "clean P", "clean R", "bbox", "scan P", "scan R", "scan unreadable"], rows),
    ]
    errors = report["errors"]
    if errors:
        shown = errors[:20]
        lines += [
            f"Errors ({len(errors)}{', first 20' if len(errors) > 20 else ''}):",
            "",
            *_table(
                ["quality", "kind", "document", "field", "expected", "got"],
                [[e["quality"], e["kind"], e["doc_id"], e["field"], e["expected"], e["got"]] for e in shown],
                "llllll",
            ),
        ]
    return lines


def _rules(reports: dict[str, dict[str, Any]] | None) -> list[str]:
    if reports is None:
        return []
    truth, pipeline = reports["truth"], reports["pipeline"]
    rows = []
    names = sorted(set(truth["rules"]) | set(pipeline["rules"]))
    for name in [*names, "**all**"]:
        t = truth["total"] if name == "**all**" else truth["rules"].get(name, {})
        p = pipeline["total"] if name == "**all**" else pipeline["rules"].get(name, {})
        rows.append(
            [
                name,
                t.get("tp", 0),
                t.get("fp", 0),
                t.get("fn", 0),
                p.get("tp", 0),
                p.get("fp", 0),
                p.get("fn", 0),
                _pct(_ratio(p.get("tp", 0), p.get("fp", 0))),
                _pct(_ratio(p.get("tp", 0), p.get("fn", 0))),
            ]
        )
    lines = [
        "## Rules",
        "",
        f"{truth['cases']} cases. *truth*: the rules run on ground-truth fields (tests the rules alone); "
        "*pipeline*: on fields extracted from the PDFs (rules + OCR + extraction). TP = expected finding "
        "reported, FP = reported but not expected, FN = expected but missing.",
        "",
        *_table(
            ["rule", "truth TP", "FP", "FN", "pipeline TP", "FP", "FN", "pipeline P", "pipeline R"],
            rows,
        ),
    ]
    issues = [
        [mode, e["kind"].upper(), e["rule"], e["case_id"], e.get("reason") or f"{e['outcome']} in {e.get('doc_id')}"]
        for mode, report in reports.items()
        for e in report["errors"]
    ]
    if issues:
        lines += ["Mismatches:", "", *_table(["mode", "kind", "rule", "case", "detail"], issues, "lllll")]
    else:
        lines += ["No mismatches.", ""]
    return lines


def _timings(
    summary: dict[str, Any],
    classification: dict[str, Any] | None,
    extraction: dict[str, Any] | None,
    rules: dict[str, dict[str, Any]] | None,
) -> list[str]:
    rows: list[list[Any]] = []
    for label, report in (
        ("classification (load + OCR + classify)", classification),
        ("extraction (load + OCR + fields)", extraction),
    ):
        if report is None or "latency" not in report:
            continue
        for quality, stats in report["latency"].items():
            if stats["count"]:
                rows.append(
                    [label, quality, stats["count"], _sec(stats["p50"]), _sec(stats["p95"]), _sec(stats["max"])]
                )
    if rules is not None:
        for mode, report in rules.items():
            stats = report.get("engine_latency")
            if stats and stats["count"]:
                rows.append(
                    [
                        f"rule engine ({mode}), per case",
                        "—",
                        stats["count"],
                        _sec(stats["p50"]),
                        _sec(stats["p95"]),
                        _sec(stats["max"]),
                    ]
                )
    tasks = summary.get("task_seconds", {})
    if not rows and not tasks:
        return []
    lines = [
        "## Timings",
        "",
        "Per document unless noted; single process, no cache. Machine-dependent: compare runs on the same host only.",
        "",
    ]
    if rows:
        lines += _table(["step", "quality", "n", "p50", "p95", "max"], rows, "llrrrr")
    if tasks:
        lines += _table(["task", "wall time"], [[k, _sec(v)] for k, v in tasks.items()])
    return lines


def _ocr_bench(bench: dict[str, Any] | None) -> list[str]:
    lines = ["## OCR benchmark", ""]
    if bench is None:
        return [
            *lines,
            "Not run yet: `make ocr-bench` (or `make eval`) measures Tesseract, Azure and Google "
            "on 200 synthetic pages.",
            "",
        ]
    providers = bench["providers"]
    names = list(providers)
    lines += [
        f"{bench['pages']} pages from the benchmark set (seed {bench['seed']}; "
        + ", ".join(f"{n} {q}" for q, n in sorted(bench["pages_by_quality"].items()))
        + f"), rendered at {bench['dpi']} dpi. Field hit rate: share of ground-truth field texts found in the "
        "page's OCR text (whitespace and case normalised). CER/WER: against the PDF text layer (clean pages). "
        "Field F1: the deterministic extractor run on each provider's words.",
        "",
    ]

    def metric(name: str, fmt: Any, always: bool = False) -> list[Any]:
        """One table row; providers that did not run show their status (cost rows: list price anyway)."""
        row: list[Any] = [name]
        for provider in names:
            result = providers[provider]
            row.append(fmt(result) if always or result["status"] == "ok" else result["status"])
        return row

    rows = [
        metric("status", lambda r: "ok"),
        metric("pages", lambda r: r["pages"]),
        metric("field hit rate - clean", lambda r: _pct(r["hit_rate"].get("clean"))),
        metric("field hit rate - scan", lambda r: _pct(r["hit_rate"].get("scan"))),
        metric("CER - clean", lambda r: _pct(r["cer"])),
        metric("WER - clean", lambda r: _pct(r["wer"])),
        metric("field F1 - clean", lambda r: _pct(r["field_f1"].get("clean"))),
        metric("field F1 - scan", lambda r: _pct(r["field_f1"].get("scan"))),
        metric("time per page p50", lambda r: _sec(r["latency"]["p50"])),
        metric("time per page p95", lambda r: _sec(r["latency"]["p95"])),
        metric("cost per page (USD)", lambda r: f"{r['cost']['per_page_usd']:.5f}", always=True),
        metric(f"cost for {bench['pages']} pages (USD)", lambda r: f"{r['cost']['total_usd']:.3f}", always=True),
    ]
    lines += _table(["metric", *names], rows, "l" + "r" * len(names))
    lines += ["Cost notes:", ""]
    lines += [f"* **{provider}**: {providers[provider]['cost_note']}" for provider in names]
    lines += [
        "",
        f"A provider without credentials is reported as „{SKIPPED}”. Only synthetic pages are sent to "
        "cloud providers by this benchmark.",
        "",
    ]
    return lines
