# ---------------------------------------------------------------------------- timing
def test_latency_summary_uses_nearest_rank_percentiles() -> None:
    stats = timing.summarize([0.5, 0.1, 0.4, 0.2, 0.3])
    assert stats == {"count": 5, "p50": 0.3, "p95": 0.5, "max": 0.5, "mean": 0.3}
    assert timing.summarize([])["p50"] is None
    assert timing.by_quality({"clean": [1.0], "scan": [3.0]})["all"]["mean"] == 2.0


# ---------------------------------------------------------------------------- report
def _write(directory: Path, name: str, data: Any) -> None:
    (directory / name).write_text(json.dumps(data))


def _eval_dir(tmp_path: Path) -> Path:
    _write(
        tmp_path,
        "summary.json",
        {
            "generated_at": "2026-10-14 10:00 UTC",
            "ocr": "tesseract",
            "dataset": {
                "cases": 2,
                "seeds": [2026],
                "documents": {"clean": 9, "scan": 1},
                "pages": {"clean": 10, "scan": 1},
                "injected_errors": 3,
                "expected_findings": 3,
                "ruleset": 16,
                "ruleset_digest": "ab" * 32,
                "fields_version": 2,
            },
            "checks": [
                {"name": "rule FP / FN on ground-truth fields", "target": "0 / 0", "value": "1 / 0", "ok": False}
            ],
            "task_seconds": {"classification": 1.25},
        },
    )
    _write(
        tmp_path,
        "classification.json",
        {
            "accuracy": 0.9,
            "correct": 9,
            "total": 10,
            "by_quality": {"clean": {"correct": 9, "total": 9}, "scan": {"correct": 0, "total": 1}},
            "errors": [{"doc_id": "D7", "expected": "faktura", "predicted": None, "quality": "scan"}],
            "latency": {"clean": timing.summarize([0.2]), "all": timing.summarize([0.2])},
        },
    )
    _write(
        tmp_path,
        "rules.json",
        {
            mode: {
                "cases": 2,
                "total": {"tp": 3, "fp": 1, "fn": 0},
                "rules": {"AMT-01": {"tp": 3, "fp": 1, "fn": 0}},
                "errors": [{"kind": "fp", "rule": "AMT-01", "case_id": "SYN-1", "reason": "Kwota | inna"}],
                "engine_latency": timing.summarize([0.01]),
            }
            for mode in ("truth", "pipeline")
        },
    )
    return tmp_path


def test_report_renders_thresholds_tables_and_mismatches(tmp_path: Path) -> None:
    text = report.render(_eval_dir(tmp_path))

    assert text.startswith("<!-- Generated by `make eval`")
    assert "| rule FP / FN on ground-truth fields | 0 / 0 | 1 / 0 | ❌ fail |" in text
    assert "| scan | 0/1 | 0.0% |" in text
    assert "| D7 | faktura | unknown | scan |" in text
    assert "| AMT-01 | 3 | 1 | 0 | 3 | 1 | 0 | 75.0% | 100.0% |" in text
    assert "Kwota \\| inna" in text  # pipes in free text cannot break the table
    assert "| classification | 1.25 s |" in text
    assert "Not run yet: `make ocr-bench`" in text


def test_report_shows_skipped_providers(tmp_path: Path) -> None:
    eval_dir = _eval_dir(tmp_path)
    bench = {
        "seed": "7300",
        "pages": 3,
        "pages_by_quality": {"clean": 2, "scan": 1},
        "dpi": 150,
        "providers": {
            "tesseract": {
                "status": "ok",
                "pages": 3,
                "hit_rate": {"clean": 1.0, "scan": 0.5},
                "cer": 0.012,
                "wer": 0.05,
                "field_f1": {"clean": 1.0, "scan": None},
                "latency": timing.summarize([1.0, 2.0, 3.0]),
                "cost": {"per_page_usd": 0.00003, "total_usd": 0.0001},
                "cost_note": "cpu",
            },
            "azure": ocr_bench.skipped("azure", 3),
            "google": ocr_bench.skipped("google", 3),
        },
    }
    _write(eval_dir, "ocr_bench.json", bench)

    text = report.render(eval_dir)

    assert "| status | ok | uruchomienie pominięte | uruchomienie pominięte |" in text
    assert "| field hit rate - scan | 50.0% | uruchomienie pominięte | uruchomienie pominięte |" in text
    assert "| cost per page (USD) | 0.00003 | 0.00150 | 0.00150 |" in text


# ---------------------------------------------------------------------------- OCR benchmark
def test_edit_distance_and_line_order() -> None:
    assert ocr_bench.edit_distance("kitten", "sitting") == 3
    assert ocr_bench.edit_distance(["a", "b", "c"], ["a", "c"]) == 1
    words = [Word("dwa", 0.3, 0.1, 0.4, 0.12), Word("jeden", 0.1, 0.1, 0.2, 0.12), Word("trzy", 0.1, 0.5, 0.2, 0.52)]
    assert ocr_bench.line_text(words) == "jeden dwa\ntrzy"


